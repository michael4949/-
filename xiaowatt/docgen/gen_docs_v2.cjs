const fs = require('fs'), path = require('path');
const {
  Document, Packer, Paragraph, TextRun, Table, TableRow, TableCell, WidthType,
  BorderStyle, ShadingType, AlignmentType, HeadingLevel, ImageRun, Header, Footer,
  PageNumber, LevelFormat, TabStopType, VerticalAlign
} = require('docx');

const ROOT = path.resolve(__dirname, '..');
const NAVY = '00367A', BLUE = '1E63B8', TXT = '1A2A3A', GREY = '5A6B7E',
  BORDER = 'C9D6E8', ZEBRA = 'F4F8FC', LIGHT = 'EAF1F9', GOLD = 'B7791F';
const FONT = { ascii: 'Calibri', hAnsi: 'Calibri', eastAsia: '微软雅黑' };
const LOGO = fs.readFileSync(path.join(ROOT, 'assets', 'logo.png'));
const CONTENT_W = 9750;

const run = (t, o = {}) => new TextRun(Object.assign({ text: t, font: FONT, size: 21, color: TXT }, o));
function body(t, o = {}) {
  /* 支持「**加粗**」内联标记 */
  const parts = t.split(/\*\*/); const children = parts.map((s, i) => run(s, Object.assign({}, o.run || {}, i % 2 ? { bold: true } : {}))).filter(x => x);
  return new Paragraph({ children, spacing: { line: 320, after: 130 }, alignment: o.align, indent: o.indent });
}
function h1(t) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 340, after: 180, line: 300 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 8, color: NAVY, space: 4 } },
    children: [new TextRun({ text: t, font: FONT, size: 31, bold: true, color: NAVY })] });
}
function h2(t) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 240, after: 130, line: 300 },
    children: [new TextRun({ text: t, font: FONT, size: 25, bold: true, color: NAVY })] });
}
function bullet(t) {
  const parts = t.split('：');
  const children = parts.length > 1 && parts[0].length <= 16 ? [run(parts[0] + '：', { bold: true }), run(parts.slice(1).join('：'))] : [run(t)];
  return new Paragraph({ children, numbering: { reference: 'bul', level: 0 }, spacing: { line: 320, after: 90 } });
}
function note(t) {
  return new Paragraph({ children: [run(t, { size: 19, color: GREY })], spacing: { line: 300, before: 60, after: 160 },
    shading: { type: ShadingType.CLEAR, fill: 'FBF6EA' }, border: { left: { style: BorderStyle.SINGLE, size: 14, color: GOLD, space: 8 } }, indent: { left: 160 } });
}
function quote(t) { /* 开篇 / 结语的定位句：深蓝左线 */
  return new Paragraph({ children: [run(t, { size: 22, color: NAVY, bold: true })], spacing: { line: 330, before: 80, after: 200 },
    shading: { type: ShadingType.CLEAR, fill: LIGHT }, border: { left: { style: BorderStyle.SINGLE, size: 18, color: NAVY, space: 10 } }, indent: { left: 180, right: 180 } });
}
function caption(t) { return new Paragraph({ children: [run(t, { size: 18, color: GREY })], alignment: AlignmentType.CENTER, spacing: { after: 200 } }); }
function pngSize(buf) { return [buf.readUInt32BE(16), buf.readUInt32BE(20)]; }
function img(p, w, h) { /* h 省略或传 0 时按 PNG 实际比例算高，避免拉伸 */
  const data = fs.readFileSync(p); const [pw, ph] = pngSize(data); const hh = h || Math.round(w * ph / pw);
  return new Paragraph({ children: [new ImageRun({ data, type: 'png', transformation: { width: w, height: hh } })], alignment: AlignmentType.CENTER, spacing: { before: 120, after: 60 } });
}
function shot(p, cap) { /* 1440×900 截图 → 620×388；外加细边框由 Word 不易做，直接放图 */
  return [img(p, 620), caption(cap)];
}
function cell(t, o = {}) {
  return new TableCell({ width: { size: o.w, type: WidthType.DXA }, shading: o.fill ? { type: ShadingType.CLEAR, fill: o.fill } : undefined,
    verticalAlign: VerticalAlign.CENTER, margins: { top: 70, bottom: 70, left: 110, right: 110 },
    children: (Array.isArray(t) ? t : [t]).map(x => new Paragraph({ children: [run(String(x), { size: o.size || 20, bold: o.bold, color: o.color || TXT })], spacing: { line: 290, after: 0 }, alignment: o.align })) });
}
function mkTable(headers, rows, widths) {
  const bd = { style: BorderStyle.SINGLE, size: 4, color: BORDER };
  return new Table({ columnWidths: widths, width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    borders: { top: bd, bottom: bd, left: bd, right: bd, insideHorizontal: bd, insideVertical: bd },
    rows: [new TableRow({ tableHeader: true, children: headers.map((hh, i) => cell(hh, { w: widths[i], fill: NAVY, color: 'FFFFFF', bold: true })) }),
      ...rows.map((r, ri) => new TableRow({ children: r.map((c, i) => cell(c, { w: widths[i], fill: ri % 2 ? ZEBRA : 'FFFFFF' })) }))] });
}
function spacer(h) { return new Paragraph({ children: [], spacing: { after: h } }); }
function pageBreak() { return new Paragraph({ children: [], pageBreakBefore: true }); }

function mkHeader(docName) {
  return new Header({ children: [new Paragraph({ tabStops: [{ type: TabStopType.RIGHT, position: CONTENT_W }],
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: NAVY, space: 3 } }, spacing: { after: 60 },
    children: [new ImageRun({ data: LOGO, type: 'png', transformation: { width: 91, height: 32 } }), new TextRun({ text: '\t南网人力资源数智化创新产品评优 · ' + docName, font: FONT, size: 17, color: GREY })] })] });
}
function mkFooter() {
  return new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [
    new TextRun({ text: '第 ', font: FONT, size: 17, color: GREY }), new TextRun({ children: [PageNumber.CURRENT], font: FONT, size: 17, color: GREY }), new TextRun({ text: ' 页', font: FONT, size: 17, color: GREY })] })] });
}
function cover(title1, title2, subtitle, infoRows) {
  const kw = 2600, vw = 5000; const bd = { style: BorderStyle.SINGLE, size: 4, color: BORDER };
  return [spacer(900),
    new Paragraph({ alignment: AlignmentType.CENTER, children: [new ImageRun({ data: LOGO, type: 'png', transformation: { width: 258, height: 91 } })], spacing: { after: 320 } }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 620 }, children: [run('南方电网公司人力资源数智化创新产品评优 · 参赛项目', { size: 22, color: GREY })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 140 }, children: [new TextRun({ text: title1, font: FONT, size: 52, bold: true, color: NAVY })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 500 }, children: [new TextRun({ text: title2, font: FONT, size: 40, bold: true, color: TXT })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 900 }, children: [run(subtitle, { size: 23, color: BLUE })] }),
    new Table({ alignment: AlignmentType.CENTER, columnWidths: [kw, vw], width: { size: kw + vw, type: WidthType.DXA },
      borders: { top: bd, bottom: bd, left: bd, right: bd, insideHorizontal: bd, insideVertical: bd },
      rows: infoRows.map(([k, v], i) => new TableRow({ children: [cell(k, { w: kw, fill: LIGHT, bold: true, align: AlignmentType.CENTER, size: 21 }), cell(v, { w: vw, fill: i % 2 ? ZEBRA : 'FFFFFF', size: 21 })] })) })];
}

