PICT = next(p for p in PS if 'r:id="rId7"' in p)
SPACER = next(p for p in PS if '<w:sz w:val="16"/>' in p and not ptext(p).strip())

def mk(mdl, text):
    """按模板段落的段落属性 + 第一个 run 的属性，生成只含一个 run 的新段落"""
    head = re.match(r'<w:p[^>]*>', mdl).group(0)
    head = re.sub(r'w14:paraId="[0-9A-F]+"', 'w14:paraId="%s"' % pid(), head)
    ppr = re.search(r'<w:pPr>.*?</w:pPr>', mdl, flags=re.S); ppr = ppr.group(0) if ppr else ''
    r = re.search(r'<w:r(?: [^>]*)?>(.*?)</w:r>', mdl, flags=re.S)
    rpr = re.search(r'<w:rPr>.*?</w:rPr>', r.group(1), flags=re.S) if r else None
    rpr = rpr.group(0) if rpr else ''
    return head + ppr + '<w:r>' + rpr + '<w:t xml:space="preserve">' + esc(text) + '</w:t></w:r></w:p>'

def mkpic(rid, w_pt, h_pt, n):
    p = PICT.replace('r:id="rId7"', 'r:id="%s"' % rid)
    p = re.sub(r'style="width:[0-9.]+pt;height:[0-9.]+pt;', 'style="width:%.1fpt;height:%.1fpt;' % (w_pt, h_pt), p)
    p = re.sub(r'o:spid="_x0000_i\d+"', 'o:spid="_x0000_i%d"' % (2000 + n), p)
    p = re.sub(r'w14:anchorId="[0-9A-F]+"', 'w14:anchorId="%s"' % pid(), p)
    p = re.sub(r'w14:paraId="[0-9A-F]+"', 'w14:paraId="%s"' % pid(), p, count=1)
    p = p.replace('<w:lastRenderedPageBreak/>', '')
    # 第一张图的 shapetype 定义只需出现一次；其余图去掉 shapetype
    if n > 0: p = re.sub(r'<v:shapetype .*?</v:shapetype>', '', p, flags=re.S)
    return p

TBLS = re.findall(r'<w:tbl>.*?</w:tbl>', DOC, flags=re.S)
def mktable(tpl_idx, rows):
    """用模板第 tpl_idx 张表（表头行 + 第一数据行）生成新表；rows = [[c1, c2, c3], ...]，单元格内 \n 分段"""
    t = TBLS[tpl_idx]; trs = re.findall(r'<w:tr[ >].*?</w:tr>', t, flags=re.S)
    pre = t[:t.index(trs[0])]; hdr = trs[0]; dtpl = trs[1]
    tcs = re.findall(r'<w:tc>.*?</w:tc>', dtpl, flags=re.S)
    out = []
    for r in rows:
        cells = []
        for i, tc in enumerate(tcs):
            tcpr = re.search(r'<w:tcPr>.*?</w:tcPr>', tc, flags=re.S).group(0)
            pm = re.search(r'<w:p[ >].*?</w:p>', tc, flags=re.S).group(0)
            paras = ''.join(mk(pm, line) for line in str(r[i]).split('\n'))
            cells.append('<w:tc>' + tcpr + paras + '</w:tc>')
        trhead = re.match(r'<w:tr[^>]*>', dtpl).group(0); trhead = re.sub(r'w14:paraId="[0-9A-F]+"', 'w14:paraId="%s"' % pid(), trhead)
        trpr = re.search(r'<w:trPr>.*?</w:trPr>', dtpl, flags=re.S); trpr = trpr.group(0) if trpr else ''
        out.append(trhead + trpr + ''.join(cells) + '</w:tr>')
    return pre + hdr + ''.join(out) + '</w:tbl>'

class Doc:
    def __init__(self): self.figs = []; self.fig_no = 0; self.tbl_no = 0
    def fig(self, path, cap, w_pt=441.0):
        if not os.path.exists(path): raise SystemExit('missing figure: ' + path)
        self.fig_no += 1; n = len(self.figs); self.figs.append(path)
        im = Image.open(path); h = w_pt * im.height / im.width
        rid = 'rId%d' % (7 + n) if n < 22 else 'rId%d' % (200 + n)
        return mkpic(rid, w_pt, h, n) + mk(M['cap'], '图%d　%s' % (self.fig_no, cap))
    def tbl(self, tpl_idx, cap, rows):
        self.tbl_no += 1
        return mk(M['tcap'], '表%d　%s' % (self.tbl_no, cap)) + mktable(tpl_idx, rows) + SPACER

def part2(d, sections):
    """第二部分大表：每节一行一格；sections = [[('h1',t)|('h2',t)|('p',t)|('fig',path,cap)], ...]"""
    t = TBLS[1]; trs = re.findall(r'<w:tr[ >].*?</w:tr>', t, flags=re.S); pre = t[:t.index(trs[0])]
    tr0 = trs[0]; trhead = re.match(r'<w:tr[^>]*>', tr0).group(0); trpr = re.search(r'<w:trPr>.*?</w:trPr>', tr0, flags=re.S); trpr = trpr.group(0) if trpr else ''
    tcpr = re.search(r'<w:tcPr>.*?</w:tcPr>', tr0, flags=re.S).group(0)
    rows = []
    for sec in sections:
        body = ''
        for it in sec:
            k = it[0]
            if k == 'h1': body += mk(M['p2h1'], it[1])
            elif k == 'h2': body += mk(M['p2h2'], it[1])
            elif k == 'p': body += mk(M['p2body'], it[1])
            elif k == 'fig': body += d.fig(it[1], it[2])
        rows.append(re.sub(r'w14:paraId="[0-9A-F]+"', 'w14:paraId="%s"' % pid(), trhead) + trpr + '<w:tc>' + tcpr + body + '</w:tc></w:tr>')
    return pre + ''.join(rows) + '</w:tbl>'

def part3(d, items):
    out = ''
    for it in items:
        k = it[0]
        if k == 'H': out += mk(M['H'], it[1])
        elif k == 'h': out += mk(M['h'], it[1])
        elif k == 'p': out += mk(M['p3'], it[1])
        elif k == 'item': out += mk(M['item'], it[1])
        elif k == 'fig': out += d.fig(it[1], it[2])
        elif k == 'tbl': out += d.tbl(it[1], it[2], it[3])
    return out

def build(name, title, areas, p2_sections, p3_items):
    d = Doc()
    body_start = DOC.index('<w:body>') + len('<w:body>')
    t0_start = DOC.index('<w:tbl>'); t0_end = DOC.index('</w:tbl>', t0_start) + len('</w:tbl>')
    head = DOC[body_start:t0_start]
    t0 = DOC[t0_start:t0_end]
    t0 = t0.replace('「小瓦特·班」班组数字画像与班组长AI助手', esc(title)).replace('（规范全称）', '深圳供电局有限公司')
    t0 = re.sub(r'□规划计划.*?□持续改进 ?', areas, t0)
    t0 = re.sub(r'<w:t>(?=□规划计划)', '<w:t xml:space="preserve">', t0)
    # 第二部分前的两段（空段 + 标题）
    t1_start = DOC.index('<w:tbl>', t0_end)
    between = DOC[t0_end:t1_start]
    # 第三部分：从「【第三部分】」段落到含 sectPr 的段落（含）
    p3h = next(p for p in PS if '【第三部分】' in ptext(p))
    p3_start = DOC.index(p3h)
    sect_p = next(p for p in PS if '<w:sectPr' in p)
    p3_end = DOC.index(sect_p) + len(sect_p)
    p4_start = DOC.index(next(p for p in PS if '【第四部分】' in ptext(p)))
    tail = DOC[p4_start:]
    doc = DOC[:body_start] + head + t0 + between + part2(d, p2_sections) + p3h + part3(d, p3_items) + sect_p + tail
    # 媒体：按图序写入；截图转 JPEG，架构图保留 PNG
    media = {}; rels = RELS; ct = CT
    if 'Extension="jpg"' not in ct and 'Extension="jpeg"' not in ct:
        ct = ct.replace('</Types>', '<Default Extension="jpg" ContentType="image/jpeg"/></Types>')
    for n, path in enumerate(d.figs):
        rid = 'rId%d' % (7 + n) if n < 22 else 'rId%d' % (200 + n)
        im = Image.open(path)
        if im.width > 2500 or 'diagrams' in path:
            if im.width > 2400: im = im.resize((2400, round(im.height * 2400 / im.width)), Image.LANCZOS)
            buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True); fn = 'image%d.png' % (n + 1)
        else:
            buf = io.BytesIO(); im.convert('RGB').save(buf, 'JPEG', quality=86, optimize=True); fn = 'image%d.jpg' % (n + 1)
        media['word/media/' + fn] = buf.getvalue()
        if n < 22: rels = re.sub(r'(<Relationship Id="%s" [^>]*Target=")media/[^"]+(")' % rid, r'\1media/%s\2' % fn, rels)
        else: rels = rels.replace('</Relationships>', '<Relationship Id="%s" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="media/%s"/></Relationships>' % (rid, fn))
    # 多余的旧图关系（22 张以内未用到的）指向不存在的文件会报错：删掉
    for n in range(len(d.figs), 22):
        rels = re.sub(r'<Relationship Id="rId%d" [^>]*/>' % (7 + n), '', rels)
    out = os.path.join(OUT, name)
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as zo:
        zo.writestr('[Content_Types].xml', ct)
        for it in Z.infolist():
            if it.filename == '[Content_Types].xml' or it.filename.startswith('word/media/'): continue
            if it.filename == 'word/document.xml': zo.writestr(it.filename, doc)
            elif it.filename == 'word/_rels/document.xml.rels': zo.writestr(it.filename, rels)
            else: zo.writestr(it.filename, Z.read(it.filename))
        for fn, data in media.items(): zo.writestr(fn, data)
    print('written', out, 'figs', len(d.figs), 'size', os.path.getsize(out) // 1024, 'KB')

