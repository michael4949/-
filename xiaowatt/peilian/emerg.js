/* ---------- 计分 ---------- */
function emgHitGroups(text, groups) {
  const n = norm(text);
  const hit = groups.filter(g => g.split('|').some(w => n.includes(norm(w)))).length;
  const need = groups.length <= 2 ? groups.length : groups.length - 1;
  return { hit, need, full: hit >= need, part: hit > 0 && hit < need };
}
function emgScore(e, a) {
  a = a || {};
  const hasN = !!(e.cs && e.cs.bad && e.cs.bad.length);
  const ptot = hasN ? EMG_CFG.pts : EMG_CFG.pts + EMG_CFG.notes, per = ptot / e.pts.length;
  const pts = e.pts.map((p, i) => {
    const r = emgHitGroups(a.pts || '', p.k);
    const st = r.full ? 'ok' : r.part ? 'part' : 'miss';
    return { i, t: p.t, st, got: st === 'ok' ? per : st === 'part' ? per / 2 : 0, per, aid: EMG_AID.test(p.t) };
  });
  const bads = hasN ? e.cs.bad.map((b, i) => {
    const r = emgHitGroups(a.cs || '', b.k);
    const per2 = EMG_CFG.notes / e.cs.bad.length;
    return { i, t: b.t, note: e.notes[b.n], st: r.full ? 'ok' : 'miss', got: r.full ? per2 : 0, per: per2 };
  }) : [];
  const rep = (e.rep || []).map(k => { const r = emgHitGroups(a.rep || '', EMG_REP[k].k); return { k, t: EMG_REP[k].t, st: r.full ? 'ok' : 'miss', got: r.full ? EMG_CFG.bonus : 0 }; });
  const sp = pts.reduce((s, x) => s + x.got, 0), sn = bads.reduce((s, x) => s + x.got, 0), sb = rep.reduce((s, x) => s + x.got, 0);
  const base = Math.round((sp + sn) * 10) / 10;
  const score = Math.min(100, Math.round((base + sb) * 10) / 10);
  const aid = pts.filter(x => x.aid);
  return {
    pts, bads, rep, sp: Math.round(sp * 10) / 10, sn: Math.round(sn * 10) / 10, sb, base, score, pass: score >= EMG_CFG.pass, ptot, hasN,
    keyMiss: bads.filter(x => x.st === 'miss').length,
    dims: {
      e1: Math.round(pts.reduce((s, x) => s + x.got, 0) / ptot * 100),
      e2: hasN ? Math.round(sn / EMG_CFG.notes * 100) : null,
      e3: rep.length ? Math.round(rep.filter(x => x.st === 'ok').length / rep.length * 100) : null,
      e4: aid.length ? Math.round(aid.reduce((s, x) => s + x.got / x.per, 0) / aid.length * 100) : null
    }
  };
}
/* AI 点评：答到什么、漏了什么（补充原文）、事例里没指出的关键问题 */
function emgReview(e, r) {
  const ok = r.pts.filter(x => x.st === 'ok').length, part = r.pts.filter(x => x.st === 'part'), miss = r.pts.filter(x => x.st === 'miss');
  const out = [];
  out.push('处置要点答到 ' + ok + ' / ' + r.pts.length + ' 项' + (part.length ? '，' + part.length + ' 项只答了一部分' : '') + (miss.length ? '，漏答 ' + miss.length + ' 项' : '') + '。');
  if (r.hasN) out.push(r.keyMiss ? '事例纠错有 ' + r.keyMiss + ' 处关键问题没有指出，注意事项是关键得分点，要背熟。' : '事例中违反注意事项的做法全部指出。');
  if (r.rep.length) { const rk = r.rep.filter(x => x.st === 'ok').length; out.push('信息报送答到 ' + rk + ' / ' + r.rep.length + ' 项' + (rk < r.rep.length ? '，电话首报、缓报原因、10 分钟续报这几条要成习惯。' : '。')); }
  return { sum: out.join(''), add: part.concat(miss).map(x => x.t) };
}
/* 标准作答（讲师演示台一键作答与语音兜底用） */
function emgModel(e, kind) {
  const pts = e.pts.map(p => p.t);
  const cs = e.cs ? e.cs.bad.map(b => b.t) : [];
  const rep = (e.rep || []).map(k => EMG_REP[k].t);
  if (kind === 'part') return { pts: pts.filter((x, i) => i % 2 === 0).join('\n'), cs: cs.slice(0, 1).join('\n'), rep: rep.slice(0, 1).join('\n') };
  if (kind === 'key') return { pts: pts.join('\n'), cs: '', rep: rep.join('\n') };
  return { pts: pts.join('\n'), cs: cs.join('\n'), rep: rep.join('\n') };
}

