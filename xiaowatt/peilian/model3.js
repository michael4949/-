/* ---------- 能力地图取数：一张地图三维度，保留各自指标体系，分层下钻 ---------- */
function m3Scores() {
  m3Init();
  const tk = tkRecords(), ex = expRecords(), exam = typeof examHist === 'function' ? examHist() : [];
  const tkAvg = tk.length ? Math.round(tk.reduce((s, r) => s + r.score, 0) / tk.length) : null;
  const exAvg = ex.length ? Math.round(ex.reduce((s, r) => s + r.core, 0) / ex.length) : null;
  const rad = typeof RADAR_NOW !== 'undefined' ? RADAR_NOW : null;
  const skill = m3Skill().map(it => {
    if (it.from === '八维岗位能力') { const i = ABILITY8.findIndex(a => a.k === it.k); const v = rad && rad[i] != null ? Math.round(rad[i] > 5 ? rad[i] : rad[i] / 5 * 100) : null; return Object.assign({ v }, it); }
    const last = tk[0];
    let v = null;
    if (last) {
      const res = tkJudge(last.rows);
      const c = res.byKind;
      v = it.k === 'tk_stage' ? Math.max(0, 100 - (c.cross || 0) * 30) : it.k === 'tk_order' ? Math.max(0, 100 - (c.order || 0) * 14)
        : it.k === 'tk_miss' ? Math.max(0, 100 - (c.miss || 0) * 6) : it.k === 'tk_text' ? Math.max(0, 100 - ((c.text || 0) + (c.level || 0)) * 10)
          : Math.max(0, 100 - (c.danger || 0) * 50);
    }
    return Object.assign({ v }, it);
  });
  const gen = M3[1].items.map(it => {
    const vs = ex.map(r => (r.dims || []).find(d => d.n === it.n)).filter(x => x && x.v != null).map(x => x.v);
    return Object.assign({ v: vs.length ? Math.round(vs.reduce((a, b) => a + b, 0) / vs.length) : null }, it);
  });
  const lead = M3[2].items.map(it => Object.assign({ v: null }, it));
  const avg = l => { const v = l.map(x => x.v).filter(x => x != null); return v.length ? Math.round(v.reduce((a, b) => a + b, 0) / v.length) : null; };
  return { skill, gen, lead, sum: { skill: avg(skill), gen: avg(gen), lead: null }, n: { tk: tk.length, ex: ex.length, exam: exam.length }, tkAvg, exAvg };
}

