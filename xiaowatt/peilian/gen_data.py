# 视位：X静 M闭唇 F唇齿 A大开 E中开 I扁 O圆 U撮 V圆扁 N微闭
def final_viseme(f):
    f = f.strip()
    # 去掉声调数字
    f = re.sub(r'\d', '', f)
    table = [
        ('iong', 'U'), ('iang', 'A'), ('uang', 'A'), ('ueng', 'U'),
        ('ang', 'A'), ('eng', 'E'), ('ing', 'I'), ('ong', 'U'),
        ('ian', 'A'), ('uan', 'A'), ('van', 'A'), ('uai', 'A'), ('iao', 'A'),
        ('iou', 'O'), ('uei', 'E'), ('uen', 'U'),
        ('ai', 'A'), ('ei', 'E'), ('ao', 'A'), ('ou', 'O'),
        ('an', 'A'), ('en', 'E'), ('in', 'I'), ('un', 'U'), ('vn', 'V'),
        ('ia', 'A'), ('ie', 'E'), ('ua', 'A'), ('uo', 'O'), ('ve', 'V'),
        ('er', 'E'), ('iu', 'O'), ('ui', 'E'),
        ('a', 'A'), ('o', 'O'), ('e', 'E'), ('i', 'I'), ('u', 'U'), ('v', 'V'),
    ]
    for k, v in table:
        if f.startswith(k) and len(f) == len(k):
            return v
    for k, v in table:
        if f.startswith(k):
            return v
    return 'E'

def onset_viseme(ini):
    if ini in ('m', 'b', 'p'):
        return 'M'
    if ini == 'f':
        return 'F'
    if ini in ('w',):
        return 'U'
    if ini in ('y',):
        return 'I'
    if ini in ('zh', 'ch', 'sh', 'r', 'z', 'c', 's'):
        return 'I'
    if ini in ('j', 'q', 'x'):
        return 'I'
    return '-'

INITIALS = ['zh', 'ch', 'sh', 'b', 'p', 'm', 'f', 'd', 't', 'n', 'l',
            'g', 'k', 'h', 'j', 'q', 'x', 'r', 'z', 'c', 's', 'y', 'w']

def char_visemes(ch):
    py = pinyin(ch, style=Style.NORMAL, errors='ignore')
    if not py or not py[0]:
        return None
    s = py[0][0]
    if not re.match(r'^[a-z]+$', s):
        return None
    ini = ''
    for i in INITIALS:
        if s.startswith(i):
            ini = i
            break
    fin = s[len(ini):]
    o = onset_viseme(ini)
    # zhi chi shi ri zi ci si → 扁
    if ini in ('zh', 'ch', 'sh', 'r', 'z', 'c', 's') and fin == 'i':
        n = 'I'
    else:
        n = final_viseme(fin) if fin else 'E'
    return (o + n)

