/* ---------- 打分：硬性 / 软性 / 结果三类指标，确定性规则 ---------- */
function expScore(text, q) {
  const t = String(text || ''), n = norm(t), len = n.length;
  const hitKeys = q.keys.filter(k => n.includes(norm(k)));
  const red = EXP_RED.filter(r => r.w.some(w => n.includes(norm(w))));
  const star = EXP_SOFT.star.filter(s => s[1].some(w => n.includes(norm(w))));
  const logic = EXP_SOFT.logic.filter(w => n.includes(norm(w))).length;
  const emp = EXP_SOFT.empathy.filter(w => n.includes(norm(w))).length;
  const res = EXP_SOFT.result.filter(w => n.includes(norm(w))).length;
  const num = (t.match(/\d+(\.\d+)?/g) || []).length + (t.match(/[一二三四五六七八九十百千万][一二三四五六七八九十百千万]?(?=[天次人年个台条分月周小])/g) || []).length;
  const hard = {
    key: Math.min(100, Math.round(hitKeys.length / Math.max(3, q.keys.length * 0.35) * 100)),
    red: red.length ? Math.max(0, 100 - red.filter(r => !r.soft).length * 60 - red.filter(r => r.soft).length * 25) : 100,
    flow: Math.round(star.length / 4 * 100)
  };
  const soft = {
    say: len < 40 ? Math.round(len / 40 * 55) : len > 460 ? 78 : Math.min(100, 55 + Math.round((len - 40) / 220 * 45)),
    emp: q.k === 'comm' ? Math.min(100, emp * 28) : Math.min(100, 58 + emp * 16), logic: Math.min(100, 40 + logic * 20), mood: red.length ? 50 : Math.min(100, 74 + logic * 5)
  };
  const outc = { done: Math.min(100, 20 + res * 16 + num * 9), sat: Math.min(100, Math.round((hard.flow + soft.emp) / 2)) };
  const avg = o => Math.round(Object.values(o).reduce((a, b) => a + b, 0) / Object.values(o).length);
  const total = Math.round(avg(hard) * 0.5 + avg(soft) * 0.3 + avg(outc) * 0.2);
  const good = [], bad = [];
  if (hitKeys.length >= 4) good.push('关键词命中 ' + hitKeys.slice(0, 5).join('、')); else bad.push('缺少本题关注的要点：' + q.keys.filter(k => !hitKeys.includes(k)).slice(0, 4).join('、'));
  if (star.length >= 3) good.push('回答有' + star.map(s => s[0]).join('→') + '的结构'); else bad.push('缺' + EXP_SOFT.star.filter(s => !star.some(x => x[0] === s[0])).map(s => s[0]).join('、') + '，建议按情境—任务—行动—结果讲一遍');
  if (res >= 2 || num >= 2) good.push('给出了可检查的结果'); else bad.push('没有给出量化结果，评委无法判断成效');
  if (emp >= 2) good.push('说到了对方的关切'); else if (q.k === 'comm') bad.push('只讲了自己做了什么，没讲对方为什么接受');
  if (logic >= 3) good.push('层次清楚'); else bad.push('层次偏平，建议先给结论再给依据');
  red.forEach(r => bad.push('合规红线：' + r.t));
  return { total, hard, soft, outc, hitKeys, red, star: star.map(s => s[0]), good, bad, len };
}
function expLevel(std, pct) {
  const item = EXP_STD.core.find(x => x.k === std) || EXP_STD.bid.find(x => x.k === std);
  if (!item) return null;
  const sc = Math.round(item.w * pct / 100);
  const lv = item.lv.find(l => sc >= l[2] && sc <= l[3]) || item.lv[item.lv.length - 1];
  return { item, sc, lv };
}
