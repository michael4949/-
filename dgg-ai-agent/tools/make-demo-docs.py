def xlsx(fn, sheet, rows, widths=None):
    wb = Workbook(); ws = wb.active; ws.title = sheet
    for r in rows: ws.append(r)
    for i, w in enumerate(widths or [], start=1):
        ws.column_dimensions[chr(64 + i)].width = w
    p = os.path.join(OUT, fn); wb.save(p)
    print('  ', fn)

def mime(s):
    """RFC 2047 编码中文显示名；不编码的话解析出来是乱码，现场很难看"""
    import base64, re
    def enc(m):
        return '=?UTF-8?B?' + base64.b64encode(m.group(0).encode('utf-8')).decode() + '?='
    return re.sub(r'[^\x00-\x7F]+', enc, s)

def eml(fn, frm, to, subject, date, body):
    frm, to, subject = mime(frm), mime(to), mime(subject)
    msg = ('From: %s\r\nTo: %s\r\nSubject: %s\r\nDate: %s\r\n'
           'MIME-Version: 1.0\r\nContent-Type: text/plain; charset="utf-8"\r\n'
           'Content-Transfer-Encoding: 8bit\r\n\r\n%s' % (frm, to, subject, date, body))
    with open(os.path.join(OUT, fn), 'wb') as f: f.write(msg.encode('utf-8'))
    print('  ', fn)

