/* 演示文档生成器（Word 部分）。产出 demo-docs/ 下的 .docx。
   内容按各模块内核 ingest() 认得的字段写：合同要有金额 / 交付期限 / 付款期次表 / 质保，
   简历要命中 RESUME_HINTS 里至少两个词，等等。造完用 tools/verify-demo-docs.js 跑真实链路验收。
   只用职务与编号，不写姓名；费用一律标「预计」。 */
const fs = require('fs');
const path = require('path');
const D = require('docx');
const { Document, Packer, Paragraph, TextRun, Table, TableRow, TableCell, WidthType, ShadingType, AlignmentType, BorderStyle } = D;
const OUT = path.join(__dirname, '..', 'demo-docs');
const FONT = '宋体';

function t(s, o) { o = o || {}; return new TextRun({ text: s, bold: !!o.b, size: o.s || 21, font: FONT }); }
function p(s, o) {
  o = o || {};
  return new Paragraph({ children: Array.isArray(s) ? s : [t(s, o)], alignment: o.align,
    spacing: { before: o.before || 0, after: o.after == null ? 60 : o.after, line: 300 } });
}
function h(s) { return p([t(s, { b: true, s: 30 })], { align: AlignmentType.CENTER, after: 160 }); }
function h2(s) { return p([t(s, { b: true, s: 24 })], { before: 140, after: 60 }); }
function tbl(widths, rows) {
  return new Table({
    columnWidths: widths,
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    rows: rows.map((r, ri) => new TableRow({
      children: r.map((c, ci) => new TableCell({
        width: { size: widths[ci], type: WidthType.DXA },
        shading: ri === 0 ? { type: ShadingType.CLEAR, fill: 'EDEDED' } : undefined,
        margins: { top: 40, bottom: 40, left: 80, right: 80 },
        children: [new Paragraph({ children: [t(String(c), { b: ri === 0, s: 20 })], spacing: { before: 0, after: 0, line: 260 } })]
      }))
    }))
  });
}
function save(name, children) {
  const doc = new Document({
    styles: { default: { document: { run: { font: FONT, size: 21 } } } },
    sections: [{ properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1100, bottom: 1100, left: 1200, right: 1200 } } }, children }]
  });
  return Packer.toBuffer(doc).then((b) => { fs.writeFileSync(path.join(OUT, name), b); console.log('  ', name); });
}

