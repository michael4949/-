function t(text, o) {
  o = o || {};
  return new TextRun({ text: text, bold: !!o.b, italics: !!o.i, color: o.c || INK,
    size: o.s || 19, font: FONT, break: o.br || 0 });
}
function p(runs, o) {
  o = o || {};
  return new Paragraph({
    children: Array.isArray(runs) ? runs : [runs],
    spacing: { before: o.before == null ? 0 : o.before, after: o.after == null ? 40 : o.after, line: o.line || 250 },
    indent: o.ind ? { left: o.ind } : undefined,
    alignment: o.align, border: o.border, pageBreakBefore: !!o.pb
  });
}
function line(s, o) { return p([t(s, o)], o); }
/* 「标签：正文」一行，标签加粗，正文接在同一行——比项目符号省行 */
function kv(label, body, o) {
  o = o || {};
  return p([t(label, { b: true, c: o.lc || KEY, s: 19 }), t(body, { s: 19 })], { ind: o.ind || 0, after: o.after == null ? 30 : o.after });
}
function h1(s) {
  return new Paragraph({
    children: [t(s, { b: true, s: 26, c: 'FFFFFF' })],
    shading: { type: ShadingType.CLEAR, fill: KEY },
    spacing: { before: 200, after: 90, line: 260 }
  });
}
function h2(s) {
  return new Paragraph({
    children: [t(s, { b: true, s: 21, c: KEY })],
    spacing: { before: 130, after: 50, line: 250 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: 'B8C6E0' } }
  });
}
function cell(text, o) {
  o = o || {};
  return new TableCell({
    width: { size: o.w, type: WidthType.DXA },
    shading: o.fill ? { type: ShadingType.CLEAR, fill: o.fill } : undefined,
    margins: { top: 30, bottom: 30, left: 70, right: 70 },
    children: [new Paragraph({
      children: [t(text, { b: !!o.b, s: o.s || 17, c: o.c || INK })],
      spacing: { before: 0, after: 0, line: 230 }, alignment: o.align
    })]
  });
}
function table(widths, rows, opt) {
  opt = opt || {};
  return new Table({
    columnWidths: widths,
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    rows: rows.map((r, ri) => new TableRow({
      tableHeader: ri === 0 && opt.header !== false,
      children: r.map((c, ci) => cell(String(c), {
        w: widths[ci], b: ri === 0 && opt.header !== false,
        fill: ri === 0 && opt.header !== false ? 'E4EAF5' : (ri % 2 === 0 ? 'F7F9FC' : undefined),
        s: opt.s || 17, align: opt.align && opt.align[ci]
      }))
    }))
  });
}
